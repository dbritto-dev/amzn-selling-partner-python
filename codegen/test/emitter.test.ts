/**
 * Fixture-spec tests for the emitter (the pattern the oagen tutorial uses):
 * parse a small spec into the IR, run the emitter, assert on the files.
 */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { generateFiles, parseSpec, type GeneratedFile } from '@workos/oagen';
import { extractExtras, extractUnionAliases } from '../src/extras.js';
import { pythonEmitter, resourceClassName } from '../src/python/index.js';
import type { EmitterOptions } from '../src/python/options.js';
import { schemaNameTransform, transformSpec } from '../src/transform.js';
import type { JsonObject } from '../src/convert.js';

const FIXTURE = {
  openapi: '3.1.0',
  info: { title: 'Widgets API', version: '1.0.0' },
  servers: [{ url: 'https://api.example.com' }],
  components: {
    schemas: {
      Widget: {
        type: 'object',
        required: ['id', 'name'],
        properties: {
          id: { type: 'string', format: 'uuid' },
          name: { type: 'string' },
          color: { type: 'string', nullable: true },
          status: { $ref: '#/components/schemas/WidgetStatus' },
          createdAt: { type: 'string', format: 'date-time' },
        },
      },
      WidgetStatus: { type: 'string', enum: ['active', 'retired'] },
      WidgetList: {
        type: 'object',
        required: ['items'],
        properties: { items: { type: 'array', items: { $ref: '#/components/schemas/Widget' } }, nextToken: { type: 'string' } },
      },
      CreateWidgetInput: { type: 'object', required: ['name'], properties: { name: { type: 'string' } } },
    },
  },
  paths: {
    '/widgets': {
      get: {
        operationId: 'listWidgets',
        summary: 'List widgets',
        tags: ['Widgets'],
        parameters: [
          { name: 'nextToken', in: 'query', schema: { type: 'string' } },
          { name: 'limit', in: 'query', schema: { type: 'integer' } },
        ],
        responses: { '200': { description: 'ok', content: { 'application/json': { schema: { $ref: '#/components/schemas/WidgetList' } } } } },
      },
      post: {
        operationId: 'createWidget',
        tags: ['Widgets'],
        requestBody: { required: true, content: { 'application/json': { schema: { $ref: '#/components/schemas/CreateWidgetInput' } } } },
        responses: { '201': { description: 'created', content: { 'application/json': { schema: { $ref: '#/components/schemas/Widget' } } } } },
      },
    },
    '/widgets/{id}': {
      delete: {
        operationId: 'deleteWidget',
        tags: ['Widgets'],
        parameters: [{ name: 'id', in: 'path', required: true, schema: { type: 'string' } }],
        responses: { '204': { description: 'gone' } },
      },
    },
  },
};

async function emit(): Promise<Record<string, string>> {
  const doc = structuredClone(FIXTURE) as unknown as JsonObject;
  const options: EmitterOptions = {
    packageName: 'widgets_sdk',
    runtimePackage: 'amzn_selling_partner',
    api: 'widgets',
    version: 'v1',
    amazon: false,
    extras: extractExtras(doc),
    unionAliases: extractUnionAliases(doc),
  };
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'emitter-test-'));
  try {
    const specPath = path.join(dir, 'spec.json');
    fs.writeFileSync(specPath, JSON.stringify(transformSpec(doc)));
    const spec = await parseSpec(specPath, { schemaNameTransform, operationIdTransform: (id) => id });
    const { files } = generateFiles(spec, pythonEmitter, {
      namespace: resourceClassName('widgets', 'v1'),
      outputDir: path.join(dir, 'out'),
      emitterOptions: options as unknown as Record<string, unknown>,
    });
    return Object.fromEntries(files.map((f: GeneratedFile) => [f.path, f.content]));
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

test('models: pydantic classes with wire aliases, enums as Literal aliases', async () => {
  const files = await emit();
  const models = files['models/widgets/v1.py'];
  assert.ok(models, `models module missing; got ${Object.keys(files).join(', ')}`);
  assert.match(models, /^"""Models for widgets v1 \(Widgets API\)\.\n\nGenerated by codegen\/ \(oagen\)/);
  assert.match(models, /^WidgetStatus: TypeAlias = Literal\["active", "retired"\]/m);
  assert.match(models, /^class Widget\(SpecModel\):/m);
  assert.match(models, /^    id: str$/m);
  assert.match(models, /^    color: str \| None = None$/m);
  assert.match(models, /^    status: WidgetStatus \| None = None$/m);
  assert.match(models, /^    created_at: datetime\.datetime \| None = Field\(default=None, alias="createdAt"\)$/m);
  assert.match(models, /^class WidgetList\(SpecModel\):/m);
  assert.match(models, /^    items: list\[Widget\]$/m);
  assert.ok(models.indexOf('class Widget(') < models.indexOf('class WidgetList('), 'classes are alphabetical');
});

test('resources: one Op per operation, typed keyword-only methods, pagination detected', async () => {
  const files = await emit();
  const resources = files['resources/widgets/v1.py'];
  assert.ok(resources, 'resources module missing');
  assert.match(resources, /^from widgets_sdk\.models\.widgets import v1 as models$/m);
  assert.match(resources, /^class WidgetsV1\(SyncResource\):/m);
  assert.match(resources, /^class AsyncWidgetsV1\(AsyncResource\):/m);
  assert.match(resources, /operation_id="listWidgets"/);
  assert.match(resources, /method="DELETE",\s*\n?\s*path="\/widgets\/\{id\}"/);
  assert.match(resources, /Pagination\(items_path="items", next_token_path="nextToken", next_token_param="nextToken"/);
  assert.match(resources, /def list_widgets\(\s*self,\s*\*,\s*next_token: str \| NotGiven = NOT_GIVEN,\s*limit: int \| NotGiven = NOT_GIVEN,/);
  assert.match(resources, /def create_widget\(\s*self,\s*\*,\s*body: models\.CreateWidgetInput \| Mapping\[str, Any\],/);
  assert.match(resources, /def delete_widget\(\s*self,\s*\*,\s*id: str,/);
  assert.match(resources, /-> SyncPage\[models\.Widget\]/);
  assert.match(resources, /-> AsyncPage\[models\.Widget\]/);
  assert.match(resources, /-> None:/);
  assert.match(resources, /__all__ = \["AsyncWidgetsV1", "WidgetsV1"\]/);
});

test('emitter refuses to run without its option bag', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'emitter-test-'));
  try {
    const specPath = path.join(dir, 'spec.json');
    fs.writeFileSync(specPath, JSON.stringify(transformSpec(structuredClone(FIXTURE) as unknown as JsonObject)));
    const spec = await parseSpec(specPath, { schemaNameTransform });
    assert.throws(() => generateFiles(spec, pythonEmitter, { namespace: 'X', outputDir: dir }), /emitterOptions\.packageName is required/);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
