import type { Emitter } from '@workos/oagen';
import { generateClient } from './client.js';
import { generateEnums } from './enums.js';
import { generateErrors } from './errors.js';
import { generateHttpClient } from './http_client.js';
import { generateModels } from './models.js';
import { generateResources } from './resources.js';

/** Notes collected while generating resources (unparsed rate limits, pagination decisions, name collisions). */
export const notes: string[] = [];

export const pythonEmitter: Emitter = {
  language: 'python',
  generateModels: (models, ctx) => generateModels(models, ctx),
  generateEnums: (enums, ctx) => generateEnums(enums, ctx),
  generateResources: (services, ctx) => {
    notes.length = 0;
    return generateResources(services, ctx, notes);
  },
  generateClient: (spec, ctx) => [...generateClient(spec, ctx), ...generateHttpClient(spec, ctx)],
  generateErrors: (ctx) => generateErrors(ctx),
  generateTests: () => [],
  fileHeader: () => '# Auto-generated by oagen. Do not edit.',
};

export { FILE_HEADER } from './header.js';
