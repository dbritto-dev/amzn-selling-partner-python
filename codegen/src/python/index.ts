/** The `python` emitter: assembles the pieces into oagen's `Emitter` interface. */
import type { Emitter } from '@workos/oagen';
import { generateClient, generateErrors } from './client.js';
import { generateEnums, generateModels } from './models.js';
import { generateResources } from './resources.js';

/** Notes collected while generating (unparsed rate limits, pagination decisions, name collisions). */
export const notes: string[] = [];

export const pythonEmitter: Emitter = {
  language: 'python',
  generateModels: (_models, ctx) => generateModels(ctx),
  generateEnums: (_enums, ctx) => generateEnums(ctx),
  generateResources: (_services, ctx) => {
    notes.length = 0;
    return generateResources(ctx, notes);
  },
  generateClient: (spec, ctx) => generateClient(spec, ctx),
  generateErrors: (ctx) => generateErrors(ctx),
  // Python tests are hand-written (pytest); nothing is generated here.
  generateTests: (_spec, _ctx) => [],
  fileHeader: () => '# Auto-generated by oagen. Do not edit.',
};
