/** The `python` emitter: assembles the pieces into oagen's `Emitter` interface. */
import fs from 'node:fs';
import path from 'node:path';
import type { Emitter, FormatCommand } from '@workos/oagen';
import { generateClient, generateErrors } from './client.js';
import { generateEnums, generateModels } from './models.js';
import { generateResources } from './resources.js';

/** Notes collected while generating (unparsed rate limits, pagination decisions, name collisions). */
export const notes: string[] = [];

export const pythonEmitter: Emitter = {
  language: 'python',
  generateModels: (_models, ctx) => generateModels(ctx),
  generateEnums: (_enums, ctx) => generateEnums(ctx),
  generateResources: (_services, ctx) => {
    notes.length = 0;
    return generateResources(ctx, notes);
  },
  generateClient: (spec, ctx) => generateClient(spec, ctx),
  generateErrors: (ctx) => generateErrors(ctx),
  // Python tests are hand-written (pytest); nothing is generated here.
  generateTests: (_spec, _ctx) => [],
  fileHeader: () => '# Auto-generated by oagen. Do not edit.',
  formatCommand: (targetDir) => ruffFormat(targetDir),
};

/** ruff over the written files: import sorting and unused-import removal, then formatting. */
function ruffFormat(targetDir: string): FormatCommand {
  const ruff = findRuff(targetDir) ?? 'ruff';
  return { cmd: 'sh', args: ['-c', `"${ruff}" check --fix --select I,F401 --quiet "$@" && "${ruff}" format --quiet "$@"`, 'ruff'] };
}

/** The ruff of the enclosing project's virtualenv (`.venv/bin/ruff` next to a `pyproject.toml`), if any. */
function findRuff(dir: string): string | null {
  for (let d = path.resolve(dir); ; d = path.dirname(d)) {
    const candidate = path.join(d, '.venv', 'bin', 'ruff');
    if (fs.existsSync(path.join(d, 'pyproject.toml')) && fs.existsSync(candidate)) return candidate;
    if (path.dirname(d) === d) return null;
  }
}
