/** The Python emitter: an oagen `Emitter` bound to one API version. */
import type { ApiSpec, Emitter, EmitterContext, Enum, GeneratedFile, Model, Service } from '@workos/oagen';
import { generateModels } from './models.js';
import { generateResources } from './resources.js';
import type { EmitterOptions } from './options.js';
import { pascalCase } from './naming.js';

export const FILE_HEADER = '# Generated by codegen/ (oagen). Do not edit by hand.';

/** Class name of the resource for an API version: `orders` + `v0` -> `OrdersV0`. */
export function resourceClassName(api: string, version: string): string {
  return pascalCase(api) + pascalCase(version.replace(/^v/, 'V'));
}

export function pythonEmitter(opts: EmitterOptions): Emitter {
  const cls = resourceClassName(opts.api, opts.version);
  return {
    language: 'python',
    generateModels(_models: Model[], ctx: EmitterContext): GeneratedFile[] {
      return generateModels(ctx.spec, ctx, opts);
    },
    generateEnums(_enums: Enum[], _ctx: EmitterContext): GeneratedFile[] {
      return []; // enums live in the models module
    },
    generateResources(_services: Service[], ctx: EmitterContext): GeneratedFile[] {
      return generateResources(ctx.spec, ctx, opts, cls);
    },
    generateClient(_spec: ApiSpec, _ctx: EmitterContext): GeneratedFile[] {
      return []; // the driver writes apis.py once for every API version
    },
    generateErrors(_ctx: EmitterContext): GeneratedFile[] {
      return []; // hand-written in runtime/_errors.py
    },
    generateTests(_spec: ApiSpec, _ctx: EmitterContext): GeneratedFile[] {
      return [];
    },
    fileHeader(): string {
      return FILE_HEADER;
    },
  };
}
