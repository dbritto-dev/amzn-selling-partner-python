"""``Op``: everything the runtime needs to execute one operation.

Resource modules generated by ``codegen/`` build one ``Op`` per operation at
import time from literals: the URL template, ordered parameter serializers
(``path()`` / ``query()`` / ``header()``), the body kind, lazily built
``TypeAdapter``s per success status, the error adapter, the rate-limit
annotation and the pagination descriptor. Nothing here looks at a spec.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any, Literal, cast
from urllib.parse import urlencode

from pydantic import BaseModel, TypeAdapter
from pydantic_core import to_json

from ._models import adapter_for
from ._pagination import CompiledPagination, Pagination, compile_pagination
from ._serializers import Encoder, ParamKind, header_serializer, path_serializer, query_serializer
from ._throttle import RateLimit
from ._types import NOT_GIVEN

BodyKind = Literal["json", "binary", "text", "form", "multipart"]
DecodeKind = Literal["json", "bytes", "text", "none"]


@dataclass(slots=True, frozen=True)
class Param:
    py_name: str
    wire_name: str
    required: bool
    location: str
    encode: Encoder = field(repr=False)


def path(
    py_name: str, wire_name: str, *, kind: ParamKind = "scalar", style: str = "simple", explode: bool = False, allow_reserved: bool = False
) -> Param:
    return Param(
        py_name, wire_name, True, "path", path_serializer(wire_name, kind, style=style, explode=explode, allow_reserved=allow_reserved)
    )


def query(
    py_name: str,
    wire_name: str,
    *,
    required: bool = False,
    kind: ParamKind = "scalar",
    style: str = "form",
    explode: bool = True,
    allow_reserved: bool = False,
) -> Param:
    return Param(
        py_name,
        wire_name,
        required,
        "query",
        query_serializer(wire_name, kind, style=style, explode=explode, allow_reserved=allow_reserved),
    )


def header(
    py_name: str, wire_name: str, *, required: bool = False, kind: ParamKind = "scalar", style: str = "simple", explode: bool = False
) -> Param:
    return Param(py_name, wire_name, required, "header", header_serializer(wire_name, kind, style=style, explode=explode))


@dataclass(slots=True, frozen=True)
class Body:
    kind: BodyKind
    content_type: str
    required: bool = True


@dataclass(slots=True, eq=False)
class Decoder:
    """Decodes a response body. JSON decoders build their ``TypeAdapter`` on first use."""

    kind: DecodeKind
    factory: Callable[[], Any] | None = field(repr=False, default=None)
    _adapter: TypeAdapter[Any] | None = field(repr=False, default=None)
    _type: Any = field(repr=False, default=None)

    @property
    def python_type(self) -> Any:
        if self.kind == "json":
            if self._type is None:
                assert self.factory is not None
                self._type = self.factory()
            return self._type
        return {"bytes": bytes, "text": str}.get(self.kind, type(None))

    @property
    def adapter(self) -> TypeAdapter[Any]:
        ad = self._adapter
        if ad is None:
            ad = adapter_for(self.python_type)
            self._adapter = ad
        return ad

    def decode(self, body: bytes, text: Callable[[], str]) -> Any:
        if self.kind == "json":
            if not body:
                return None  # 204-style success with a declared schema but no body
            ad = self._adapter
            if ad is None:
                ad = self.adapter
            return ad.validate_json(body)
        if self.kind == "bytes":
            return body
        if self.kind == "text":
            return text()
        return None

    def warm(self) -> None:
        if self.kind == "json":
            self.adapter  # noqa: B018


def json_decoder(factory: Callable[[], Any]) -> Decoder:
    """Decoder over the type returned by ``factory`` (called once, lazily)."""
    return Decoder("json", factory)


NONE = Decoder("none")
TEXT = Decoder("text")
BYTES = Decoder("bytes")


@dataclass(slots=True, frozen=True, kw_only=True)
class Op:
    key: str
    name: str
    operation_id: str
    api: str = ""
    version: str = ""
    method: str  # upper-case
    path: str
    url_template: str  # str.format template with positional placeholders
    path_params: tuple[Param, ...] = ()
    query_params: tuple[Param, ...] = ()
    header_params: tuple[Param, ...] = ()
    body: Body | None = None
    default_decoder: Decoder = NONE
    decoders: dict[int, Decoder] = field(default_factory=dict[int, Decoder], repr=False)
    error_decoders: dict[int, Decoder] = field(default_factory=dict[int, Decoder], repr=False)
    default_error: Decoder | None = field(default=None, repr=False)
    stream_default: bool = False
    rate_limit: RateLimit | None = None
    pagination: Pagination | None = None
    deprecated: bool = False
    doc: str | None = field(default=None, repr=False)
    tags: tuple[str, ...] = ()
    #: free-form per-operation data (plugins, tests)
    annotations: dict[str, Any] = field(default_factory=dict[str, Any], repr=False)
    # derived (set in __post_init__)
    accepted: frozenset[str] = field(init=False, repr=False)
    required: tuple[str, ...] = field(init=False, repr=False)
    static_path: bool = field(init=False, repr=False)
    compiled_pagination: CompiledPagination | None = field(init=False, repr=False)

    def __post_init__(self) -> None:
        params = [*self.path_params, *self.query_params, *self.header_params]
        names = {p.py_name for p in params}
        if self.body is not None:
            names.add("body")
        required = [p.py_name for p in params if p.required]
        if self.body is not None and self.body.required:
            required.append("body")
        object.__setattr__(self, "accepted", frozenset(names))
        object.__setattr__(self, "required", tuple(required))
        object.__setattr__(self, "static_path", not self.path_params)
        desc = self.pagination
        object.__setattr__(
            self,
            "compiled_pagination",
            compile_pagination(desc, self.query_params, self.path_params, self.header_params) if desc is not None else None,
        )

    # -- request building (hot path) ------------------------------------------------

    def build_url(self, base_url: str, kwargs: dict[str, Any]) -> str:
        if self.static_path:
            url = base_url + self.url_template
        else:
            url = base_url + self.url_template.format(*[p.encode(kwargs[p.py_name]) for p in self.path_params])
        if self.query_params:
            parts: list[str] = []
            for p in self.query_params:
                v = kwargs.get(p.py_name, NOT_GIVEN)
                if v is not NOT_GIVEN and v is not None:
                    parts.append(p.encode(v))
            if parts:
                url = url + "?" + "&".join(parts)
        return url

    def build_headers(self, kwargs: dict[str, Any]) -> tuple[tuple[str, str], ...]:
        return tuple(
            (p.wire_name, p.encode(kwargs[p.py_name]))
            for p in self.header_params
            if kwargs.get(p.py_name, NOT_GIVEN) is not NOT_GIVEN and kwargs[p.py_name] is not None
        )

    def encode_body(self, value: Any) -> tuple[bytes, str] | None:
        body = self.body
        if body is None:
            return None
        if value is NOT_GIVEN:
            if body.required:
                raise TypeError(f"{self.name}() missing required argument: 'body'")
            return None
        if body.kind == "json":
            if isinstance(value, BaseModel):
                return value.__pydantic_serializer__.to_json(value, by_alias=True, exclude_none=True), body.content_type
            return to_json(value, by_alias=True, exclude_none=True), body.content_type
        if body.kind == "binary":
            if isinstance(value, str):
                value = value.encode()
            return bytes(value), body.content_type
        if body.kind == "text":
            return (value if isinstance(value, bytes) else str(value).encode()), body.content_type
        if isinstance(value, (bytes, bytearray, memoryview)):
            return bytes(cast(bytes, value)), body.content_type  # pre-encoded form/multipart payload
        if body.kind == "form" and isinstance(value, dict):
            return urlencode(cast(dict[str, Any], value), doseq=True).encode(), body.content_type
        raise TypeError(f"{self.name}: a {body.kind!r} body must be passed as pre-encoded bytes")

    def check_kwargs(self, kwargs: dict[str, Any]) -> None:
        keys = kwargs.keys()
        if not keys <= self.accepted:
            unexpected = sorted(keys - self.accepted)
            raise TypeError(f"{self.name}() got unexpected keyword argument(s): {', '.join(unexpected)}")
        for r in self.required:
            if r not in kwargs or kwargs[r] is NOT_GIVEN:
                raise TypeError(f"{self.name}() missing required keyword argument: {r!r}")

    def decoder_for(self, status: int) -> Decoder:
        d = self.decoders.get(status)
        return d if d is not None else self.default_decoder

    def warm(self) -> None:
        """Build every adapter this operation needs (preload)."""
        for d in self.decoders.values():
            d.warm()
        self.default_decoder.warm()
        for d in self.error_decoders.values():
            d.warm()
        if self.default_error is not None:
            self.default_error.warm()

    @property
    def returns_page(self) -> bool:
        return self.compiled_pagination is not None

    @property
    def params(self) -> tuple[Param, ...]:
        return (*self.path_params, *self.query_params, *self.header_params)


#: Backwards-compatible name.
CompiledOp = Op

__all__ = ["BYTES", "NONE", "TEXT", "Body", "CompiledOp", "Decoder", "Op", "Param", "header", "json_decoder", "path", "query"]
