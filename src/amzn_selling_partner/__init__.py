"""Amazon Selling Partner API for Python.

``sdk/`` is generated by ``codegen/`` (an oagen emitter) from Amazon's API
models: ``sdk.client.Client`` / ``AsyncClient`` expose one resource per API
version (``client.orders_v0.list_orders(...)``, ``client.orders`` for the
latest version), ``sdk.models`` the pydantic models, ``sdk.http_client`` the
HTTP layer (retries, throttling, auth hook) and ``sdk.errors`` the exceptions.

``SellingPartner`` / ``AsyncSellingPartner`` (``plugins.amazon_spapi``) add the
Amazon specifics on top: regions, Login-with-Amazon auth with Restricted Data
Tokens and grantless scopes, document helpers and notification models. The
``client``, ``reports``, ``vendor`` and ``utils`` subpackages keep the 0.1.x
entry points working (see ``MIGRATION.md``).
"""

