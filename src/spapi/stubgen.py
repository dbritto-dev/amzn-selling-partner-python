"""Emit ``.pyi`` stubs from the IR.

Stubs are optional and never executed. They are written into a directory that
type checkers read through ``stubPath`` (pyright) / ``mypy_path`` (mypy), so
they augment the runtime package without replacing it:

* ``<out>/spapi/models/<api>/<version>.pyi`` – one ``BaseModel`` subclass per
  object schema (with the raw-mode ``TypedDict`` twin ``<Name>Dict``), type
  aliases for the rest.
* ``<out>/spapi/resources/<api>/<version>.pyi`` – ``<Api>`` / ``Async<Api>``
  resource classes with typed keyword-only parameters; paginated operations
  return ``SyncPage[T]`` / ``AsyncPage[T]``, ``raw=True`` overloads return the
  ``TypedDict`` variants.
* ``<out>/spapi/apis.pyi`` – ``SellingPartnerAPIs`` / ``AsyncSellingPartnerAPIs``
  protocols listing every ``client.<api>.<version>`` attribute.

CLI::

    python -m spapi.stubgen [--out stubs] [--specs DIR ...] [--check]
"""

from __future__ import annotations

import argparse
import difflib
import filecmp
import os
import pathlib
import shutil
import sys
import tempfile
from collections.abc import Iterable
from typing import Any

from .compile.naming import class_name, field_name, method_name, param_name, pascal_case, snake_case
from .compile.operations import detect_pagination
from .compile.typenames import type_expr
from .runtime._pagination import Pagination
from .spec.ir import Document, Operation, Schema

HEADER = "# Generated by `python -m spapi.stubgen`; do not edit.\n"


def _is_object(document: Document, schema: Schema) -> bool:
    s = document.resolve(schema)
    return bool(s.properties) or bool(s.all_of)


def _merged(document: Document, schema: Schema) -> Schema:
    s = document.resolve(schema)
    if not s.all_of:
        return s
    props: dict[str, Schema] = {}
    required: set[str] = set()
    for part in s.all_of:
        m = _merged(document, part)
        props.update(m.properties)
        required |= set(m.required)
    props.update(s.properties)
    required |= set(s.required)
    return Schema(name=s.name, type="object", properties=props, required=frozenset(required), description=s.description)


class _ModelWriter:
    def __init__(self, document: Document) -> None:
        self.document = document
        self.classes: dict[str, Schema] = {}  # class name -> object schema
        self.aliases: dict[str, str] = {}
        self.order: list[str] = []

    def collect(self) -> None:
        for name, schema in self.document.schemas.items():
            cls = class_name(name)
            if _is_object(self.document, schema):
                self._collect_object(cls, schema)
            else:
                self.aliases[cls] = type_expr(self.document, schema, cls, literal_enums=True)
                self._collect_inline(schema, cls)

    def _collect_object(self, cls: str, schema: Schema) -> None:
        if cls in self.classes:
            return
        merged = _merged(self.document, schema)
        self.classes[cls] = merged
        self.order.append(cls)
        for wire, prop in merged.properties.items():
            self._collect_inline(prop, f"{cls}{pascal_case(wire)}")

    def _collect_inline(self, schema: Schema, hint: str) -> None:
        if schema.ref is not None:
            return
        if schema.properties or schema.all_of:
            self._collect_object(class_name(hint), schema)
            return
        if schema.items is not None:
            self._collect_inline(schema.items, hint + "Item")
        if isinstance(schema.additional_properties, Schema):
            self._collect_inline(schema.additional_properties, hint + "Value")
        for i, v in enumerate(schema.one_of or schema.any_of):
            self._collect_inline(v, f"{hint}Variant{i + 1}")

    def render(self) -> str:
        out: list[str] = []
        for cls in self.order:
            schema = self.classes[cls]
            out.append(f"\nclass {cls}(BaseModel):")
            if schema.description:
                out.append(f'    """{_doc(schema.description)}"""')
            used: set[str] = set()
            if not schema.properties:
                out.append("    pass")
            for wire, prop in schema.properties.items():
                py = field_name(wire)
                if py in used:
                    n = 2
                    while f"{py}_{n}" in used:
                        n += 1
                    py = f"{py}_{n}"
                used.add(py)
                ann = type_expr(self.document, prop, f"{cls}{pascal_case(wire)}")
                required = wire in schema.required
                if not required and not ann.endswith("| None"):
                    ann = f"{ann} | None"
                alias = f'alias="{wire}"' if wire != py else ""
                if required:
                    out.append(f"    {py}: {ann}" + (f" = Field({alias})" if alias else ""))
                else:
                    out.append(f"    {py}: {ann} = Field(default=None{', ' + alias if alias else ''})")
            out.append(f"    def __init__(self, **data: Any) -> None: ...")
        out.append("\n# raw-mode shapes (``raw=True``)")
        for cls in self.order:
            schema = self.classes[cls]
            out.append(f"\nclass {cls}Dict(TypedDict, total=False):")
            if not schema.properties:
                out.append("    pass")
            for wire, prop in schema.properties.items():
                ann = type_expr(self.document, prop, f"{cls}{pascal_case(wire)}", dict_suffix="Dict")
                key = wire if wire.isidentifier() else None
                if key is None:
                    continue  # non-identifier keys cannot be expressed in class syntax
                out.append(f"    {key}: {ann}")
        if self.aliases:
            out.append("\n# type aliases")
            for name, expr in self.aliases.items():
                out.append(f"{name} = {expr}")
        body = "\n".join(out) + "\n"
        return HEADER + "from __future__ import annotations\n" + _imports(body, pydantic=("BaseModel", "Field"), typing=("Any", "Literal", "TypedDict")) + body


def _imports(body: str, *, typing: tuple[str, ...], pydantic: tuple[str, ...] = ()) -> str:
    """Import lines for the names actually used in ``body``."""
    lines: list[str] = []
    if "datetime." in body:
        lines.append("import datetime")
    used_typing = [n for n in typing if (n + "[" in body or f"({n}" in body or f"@{n}" in body or f": {n}" in body or f"[{n}]" in body or f", {n}]" in body or f"| {n}" in body or f"-> {n}" in body)]
    if used_typing:
        lines.append(f"from typing import {', '.join(used_typing)}")
    used_pyd = [n for n in pydantic if n + "(" in body or f"({n})" in body]
    if used_pyd:
        lines.append(f"\nfrom pydantic import {', '.join(used_pyd)}")
    return "\n".join(lines) + "\n" if lines else ""


def _doc(text: str) -> str:
    return text.strip().replace('"""', "'''").replace("\\", "\\\\").splitlines()[0][:200]


def _return_type(document: Document, op: Operation, *, dict_suffix: str) -> str:
    for code, resp in op.responses.items():
        if code.startswith("2"):
            js = resp.json_schema
            if js is not None:
                return type_expr(document, js, pascal_case(op.operation_id) + "Response", model_prefix="models.", dict_suffix=dict_suffix)
            if not resp.content:
                return "None"
            media = next(iter(resp.content))
            if media == "text/event-stream":
                return "Stream"
            return "str" if media.startswith("text/") else "bytes"
    return "None"


def _items_type(document: Document, op: Operation, pagination: Pagination, *, dict_suffix: str) -> str:
    success = next((r for c, r in op.responses.items() if c.startswith("2")), None)
    if success is None or success.json_schema is None:
        return "Any"
    schema: Schema | None = success.json_schema
    for part in pagination.items_path.split("."):
        if not part or schema is None:
            break
        resolved = _merged(document, schema)
        schema = resolved.properties.get(part)
    if schema is None:
        return "Any"
    if pagination.items_is_object:
        return type_expr(document, schema, "Items", model_prefix="models.", dict_suffix=dict_suffix)
    resolved = document.resolve(schema)
    if resolved.type == "array" and resolved.items is not None:
        return type_expr(document, resolved.items, "Item", model_prefix="models.", dict_suffix=dict_suffix)
    return "Any"


def render_resource(document: Document, api: str, version: str, class_base: str) -> str:
    out: list[str] = []
    seen: dict[str, int] = {}
    for is_async in (False, True):
        cls = ("Async" if is_async else "") + class_base
        out.append(f"\nclass {cls}({'AsyncResource' if is_async else 'SyncResource'}):")
        out.append("    models: Any")
        seen = {}
        for op in document.operations:
            name = method_name(op.operation_id)
            if name in seen:
                name = f"{name}_{op.method.lower()}"
            seen[name] = 1
            out.extend(_render_method(document, op, name, is_async))
        if not document.operations:
            out.append("    pass")
    body = "\n".join(out) + "\n"
    head = HEADER + "from __future__ import annotations\n" + _imports(body, typing=("Any", "Literal", "overload"))
    head += f"from spapi.compile.resources import AsyncResource, SyncResource\nfrom spapi.models.{api} import {version} as models\n"
    runtime = [n for n in ("NOT_GIVEN", "NotGiven", "Pagination", "RequestOptions") if n in body]
    if runtime:
        head += f"from spapi.runtime import {', '.join(runtime)}\n"
    pages = [n for n in ("AsyncPage", "SyncPage") if n + "[" in body]
    if pages:
        head += f"from spapi.runtime._pagination import {', '.join(pages)}\n"
    streams = [n for n in ("AsyncStream", "Stream") if f"-> {n}" in body]
    if streams:
        head += f"from spapi.runtime._stream import {', '.join(streams)}\n"
    if "models." not in body:
        head = head.replace(f"from spapi.models.{api} import {version} as models\n", "")
    return head + body


def _render_method(document: Document, op: Operation, name: str, is_async: bool) -> list[str]:
    params: list[tuple[str, str, bool]] = []  # (py, annotation, required)
    used: set[str] = set()

    def unique(py: str) -> str:
        cand, n = py, 2
        while cand in used:
            cand = f"{py}_{n}"
            n += 1
        used.add(cand)
        return cand

    for p in op.parameters:
        if p.location == "cookie":
            continue
        params.append((unique(param_name(p.name)), type_expr(document, p.schema, pascal_case(p.name), model_prefix="models."), p.required or p.location == "path"))
    if op.request_body is not None:
        js = op.request_body.json_schema
        if js is not None:
            ann = type_expr(document, js, pascal_case(op.operation_id) + "Body", model_prefix="models.")
            dict_ann = type_expr(document, js, pascal_case(op.operation_id) + "Body", model_prefix="models.", dict_suffix="Dict")
            ann = f"{ann} | {dict_ann}" if dict_ann != ann else ann
        else:
            media = next(iter(op.request_body.content), "")
            ann = "str" if media.startswith("text/") else "bytes | dict[str, Any]" if "form" in media else "bytes"
        params.append(("body", ann, op.request_body.required))
    params.sort(key=lambda p: not p[2])
    pagination = op.annotations.get("pagination", detect_pagination(op, document)) if "pagination" in op.annotations else detect_pagination(op, document)
    ret_model = _return_type(document, op, dict_suffix="")
    ret_dict = _return_type(document, op, dict_suffix="Dict")
    if ret_model == "Stream":
        ret_model = ret_dict = "AsyncStream" if is_async else "Stream"
    if pagination is not None:
        page = "AsyncPage" if is_async else "SyncPage"
        ret_model = f"{page}[{_items_type(document, op, pagination, dict_suffix='')}]"
        ret_dict = f"{page}[{_items_type(document, op, pagination, dict_suffix='Dict')}]"
    prefix = "    async def" if is_async else "    def"
    lines: list[str] = []
    doc = (op.summary or op.description or "").strip().splitlines()[0] if (op.summary or op.description) else ""
    doc = doc.replace('"""', "'''")[:200]

    def sig(raw_ann: str, raw_default: str) -> str:
        parts = ["self", "*"]
        for py, ann, required in params:
            parts.append(f"{py}: {ann}" if required else f"{py}: {ann} | NotGiven = NOT_GIVEN")
        parts.append(f"raw: {raw_ann}{raw_default}")
        parts.append("paginate: Pagination | None | NotGiven = NOT_GIVEN")
        parts.append("request_options: RequestOptions | None = None")
        return ", ".join(parts)

    if ret_dict != ret_model:
        lines.append("    @overload")
        lines.append(f"{prefix} {name}({sig('Literal[False]', ' = ...')}) -> {ret_model}: ...")
        lines.append("    @overload")
        lines.append(f"{prefix} {name}({sig('Literal[True]', '')}) -> {ret_dict}: ...")
    lines.append(f"{prefix} {name}({sig('bool', ' = False')}) -> {ret_model}:")
    lines.append(f'        """{doc}"""' if doc else "        ...")
    return lines


def generate(specs: Iterable[tuple[str, str, pathlib.Path]], out_dir: pathlib.Path, *, plugins: Iterable[Any] = ()) -> list[pathlib.Path]:
    """Write stubs for ``(api, version, spec path)`` triples; returns the files written."""
    from .plugins import run_plugins
    from .spec.loader import load_document

    written: list[pathlib.Path] = []
    apis: dict[str, list[str]] = {}
    for api, version, path in specs:
        document = run_plugins(load_document(path), plugins)
        apis.setdefault(api, []).append(version)
        mw = _ModelWriter(document)
        mw.collect()
        model_file = out_dir / "spapi" / "models" / api / f"{version}.pyi"
        model_file.parent.mkdir(parents=True, exist_ok=True)
        model_file.write_text(mw.render())
        written.append(model_file)
        class_base = "".join(p.capitalize() for p in snake_case(api).split("_"))
        res_file = out_dir / "spapi" / "resources" / api / f"{version}.pyi"
        res_file.parent.mkdir(parents=True, exist_ok=True)
        res_file.write_text(render_resource(document, api, version, class_base))
        written.append(res_file)
        for d in (model_file.parent, res_file.parent):
            init = d / "__init__.pyi"
            if not init.exists():
                init.write_text(HEADER)
                written.append(init)
    for sub in ("models", "resources"):
        init = out_dir / "spapi" / sub / "__init__.pyi"
        init.write_text(HEADER)
        written.append(init)
    written.append(_write_apis(out_dir, apis))
    return written


def _write_apis(out_dir: pathlib.Path, apis: dict[str, list[str]]) -> pathlib.Path:
    from .client import version_key

    out = [HEADER, "from __future__ import annotations\n", "from typing import Protocol\n"]
    for api in sorted(apis):
        for v in sorted(apis[api]):
            out.append(f"from spapi.resources.{api} import {v} as _{api}_{v}")
    for is_async in (False, True):
        pre = "Async" if is_async else ""
        for api in sorted(apis):
            base = "".join(p.capitalize() for p in snake_case(api).split("_"))
            out.append(f"\nclass {pre}{base}Versions(Protocol):")
            versions = sorted(apis[api], key=version_key)
            for v in versions:
                out.append(f"    {v}: _{api}_{v}.{pre}{base}")
            out.append(f"    latest: _{api}_{versions[-1]}.{pre}{base}")
        out.append(f"\nclass {pre}SellingPartnerAPIs(Protocol):")
        for api in sorted(apis):
            base = "".join(p.capitalize() for p in snake_case(api).split("_"))
            out.append(f"    {api}: {pre}{base}Versions")
    path = out_dir / "spapi" / "apis.pyi"
    path.write_text("\n".join(out) + "\n")
    return path


def amazon_specs() -> tuple[list[tuple[str, str, pathlib.Path]], list[Any]]:
    from .plugins.amazon_spapi import AmazonPlugin, default_spec_dir

    plugin = AmazonPlugin()
    triples: list[tuple[str, str, pathlib.Path]] = []
    for path in plugin.spec_files(default_spec_dir()):
        named = plugin.api_naming(path)
        if named is not None:
            triples.append((named[0], named[1], path))
    return triples, [plugin]


def check(out_dir: pathlib.Path, specs: list[tuple[str, str, pathlib.Path]], plugins: list[Any]) -> list[str]:
    """Regenerate into a temp dir and return a list of differences (empty = up to date)."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = pathlib.Path(tmp)
        generate(specs, tmp_dir, plugins=plugins)
        diffs: list[str] = []
        for new in sorted(tmp_dir.rglob("*.pyi")):
            rel = new.relative_to(tmp_dir)
            old = out_dir / rel
            if not old.exists():
                diffs.append(f"missing: {rel}")
            elif not filecmp.cmp(old, new, shallow=False):
                delta = difflib.unified_diff(old.read_text().splitlines(), new.read_text().splitlines(), str(rel), str(rel), lineterm="", n=1)
                diffs.append("\n".join(list(delta)[:40]))
        for old in sorted(out_dir.rglob("*.pyi")):
            rel = old.relative_to(out_dir)
            if not (tmp_dir / rel).exists():
                diffs.append(f"stale: {rel}")
        return diffs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate .pyi stubs from API specs.")
    parser.add_argument("--out", default="stubs", help="output directory (default: stubs)")
    parser.add_argument("--specs", nargs="*", help="spec files/directories (default: the bundled Amazon models)")
    parser.add_argument("--check", action="store_true", help="fail if the stubs in --out are not up to date")
    args = parser.parse_args(argv)
    out_dir = pathlib.Path(args.out)
    plugins: list[Any]
    if args.specs:
        from .client import default_api_naming, normalize_version
        from .plugins import default_spec_files
        from .spec.loader import load_document

        triples = []
        for root in args.specs:
            for path in default_spec_files(pathlib.Path(root)):
                api, version = default_api_naming(path)
                if version is None:
                    version = normalize_version(load_document(path).version)
                triples.append((api, version, path))
        plugins = []
    else:
        triples, plugins = amazon_specs()
    if args.check:
        diffs = check(out_dir, triples, plugins)
        if diffs:
            print("\n".join(diffs))
            print(f"stubs in {out_dir} are out of date ({len(diffs)} differences); run: python -m spapi.stubgen --out {out_dir}")
            return 1
        print(f"stubs in {out_dir} are up to date")
        return 0
    if out_dir.exists():
        shutil.rmtree(out_dir / "spapi", ignore_errors=True)
    written = generate(triples, out_dir, plugins=plugins)
    print(f"wrote {len(written)} files under {out_dir}{os.sep}spapi")
    return 0


if __name__ == "__main__":
    sys.exit(main())
